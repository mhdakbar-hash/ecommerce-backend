package com.akbar.ecommerce_backend.payment.dto;

import com.akbar.ecommerce_backend.payment.enums.PaymentMethod;
import com.akbar.ecommerce_backend.payment.enums.PaymentStatus;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDateTime;

@AllArgsConstructor
@NoArgsConstructor
@Getter
@Setter
@Builder
public class PaymentResponseDTO {

    @Schema(
            description = "Unique identifier of the payment",
            example = "1"
    )
    private Long id;


    @Schema(
            description = "ID of the order associated with the payment",
            example = "101"
    )
    private Long orderId;


    @Schema(
            description = "Payment amount derived from the order total",
            example = "1499.00"
    )
    private BigDecimal amount;


    @Schema(
            description = "Current status of the payment",
            example = "INITIATED"
    )
    private PaymentStatus status;


    @Schema(
            description = "Payment method selected by the customer",
            example = "UPI"
    )
    private PaymentMethod paymentMethod;


    @Schema(
            description = "Transaction reference generated by the payment gateway",
            example = "MOCK-TXN-8F72A91"
    )
    private String transactionReference;


    @Schema(
            description = "Transaction reference generated for the refund",
            example = "MOCK-REFUND-8F72A91"
    )
    private String refundReference;


    @Schema(
            description = "Date and time when the payment was created",
            example = "2026-09-23T14:45:00"
    )
    private LocalDateTime createdAt;

}